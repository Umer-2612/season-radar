// Pulls official CSO retail data and writes src/data/cso.json.
// Run: node scripts/fetch-cso.mjs
import { writeFileSync } from "node:fs";

const API = "https://ws.cso.ie/public/api.restful/PxStat.Data.Cube_API.ReadDataset";
const CHRISTMAS_YEARS = [2021, 2022, 2023, 2024, 2025];
const MOMENTUM_MONTHS = 3;

const CATEGORIES = [
  { id: "all", label: "All Irish retail", nace: "All retail businesses, excluding motor trades" },
  { id: "toys", label: "Toys, gifts, sports & jewellery", nace: "Other retail sales (4753,4763 to 4765,4776 to 4778)" },
  { id: "electrical", label: "Electronics & electrical", nace: "Retail sale of electrical goods (4741 to 4743,4754)" },
  { id: "clothing", label: "Clothes & shoes", nace: "Retail sale of textiles, clothing and footwear (4751,4771,4772)" },
  { id: "beauty", label: "Pharmacy & beauty", nace: "Retail sale of pharmaceutical, medical and cosmetic articles (4773 to 4775)" },
  { id: "books", label: "Books & stationery", nace: "Retail sale of books, newspapers and stationery (4761,4762)" },
  { id: "home", label: "Furniture & lighting", nace: "Retail sale of furniture and lighting (4759)" },
  { id: "hardware", label: "Hardware & DIY", nace: "Retail sale of hardware, paints and glass (4752)" },
  { id: "food", label: "Specialist food & drink", nace: "Retail sale of food, beverages and tobacco in specialised stores (4721 to 4729)" },
];

const load = async (code) => {
  const res = await fetch(`${API}/${code}/JSON-stat/2.0/en`);
  if (!res.ok) throw new Error(`CSO ${code} failed: ${res.status}`);
  return res.json();
};

const cube = (d) => {
  const [statKey, timeKey, naceKey] = d.id;
  const dim = (k) => d.dimension[k].category;
  const keys = (k) => (Array.isArray(dim(k).index) ? dim(k).index : Object.keys(dim(k).index));
  const stats = keys(statKey);
  const months = keys(timeKey);
  const naces = keys(naceKey);
  const naceByLabel = Object.fromEntries(naces.map((n) => [dim(naceKey).label[n], n]));
  const monthLabel = (m) => dim(timeKey).label[m];
  const get = (statLabel, naceLabel, month) => {
    const s = stats.findIndex((x) => dim(statKey).label[x] === statLabel);
    const i = (s * months.length + months.indexOf(month)) * naces.length + naces.indexOf(naceByLabel[naceLabel]);
    return d.value[i];
  };
  return { months, monthLabel, get };
};

const pct = (a, b) => Math.round((a / b - 1) * 1000) / 10;

const main = async () => {
  const [volumeRaw, onlineRaw] = await Promise.all([load("RSM08"), load("RSM07")]);
  const vol = cube(volumeRaw);
  const online = cube(onlineRaw);
  const VOLUME = "Retail Sales Index Volume Unadjusted";
  const ONLINE = "Turnover generated by Online Sales";

  const monthsOf = (c, y, names) => c.months.filter((m) => names.some((n) => c.monthLabel(m) === `${y} ${n}`));
  const latest = vol.months.at(-1);
  const recent = vol.months.slice(-MOMENTUM_MONTHS);
  const sameLastYear = recent.map((m) => vol.months.find((x) => vol.monthLabel(x) === vol.monthLabel(m).replace(/^\d{4}/, (y) => String(+y - 1))));

  const categories = CATEGORIES.map((c) => {
    const christmas = CHRISTMAS_YEARS.map((y) => {
      const ms = monthsOf(vol, y, ["November", "December"]);
      return Math.round(ms.reduce((s, m) => s + vol.get(VOLUME, c.nace, m), 0) * 10) / 10;
    });
    const year2025 = monthsOf(vol, 2025, ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]);
    const avgMonth = year2025.reduce((s, m) => s + vol.get(VOLUME, c.nace, m), 0) / year2025.length;
    const dec2025 = vol.get(VOLUME, c.nace, monthsOf(vol, 2025, ["December"])[0]);
    const sum = (ms) => ms.reduce((s, m) => s + vol.get(VOLUME, c.nace, m), 0);
    const onlineDec = (y) => {
      const m = monthsOf(online, y, ["December"])[0];
      return m ? online.get(ONLINE, c.nace, m) ?? null : null;
    };
    const monthSum = (y, names) => sum(monthsOf(vol, y, names));
    const nov = (y) => vol.get(VOLUME, c.nace, monthsOf(vol, y, ["November"])[0]);
    const autumn = (y) => monthSum(y, ["August", "September", "October"]);
    const xmas = (y) => monthSum(y, ["November", "December"]);
    const backtest = [2022, 2023, 2024, 2025].map((y) => ({
      year: y,
      signal: pct(autumn(y), autumn(y - 1)),
      outcome: pct(xmas(y), xmas(y - 1)),
    }));
    return {
      id: c.id,
      novemberLift: Math.round((nov(2025) / avgMonth - 1) * 100),
      lastBlackFridayChange: pct(nov(2025), nov(2024)),
      backtest,
      label: c.label,
      csoGroup: c.nace,
      christmas,
      lastChristmasChange: pct(christmas.at(-1), christmas.at(-2)),
      decemberLift: Math.round((dec2025 / avgMonth - 1) * 100),
      momentum2026: pct(sum(recent), sum(sameLastYear)),
      onlineShareDec: { 2024: onlineDec(2024), 2025: onlineDec(2025) },
    };
  });

  const market = categories.find((c) => c.id === "all");
  const scored = categories.map((c) => {
    const hits = c.backtest.filter((b, i) => {
      const m = market.backtest[i];
      return Math.sign(b.signal - m.signal) === Math.sign(b.outcome - m.outcome);
    }).length;
    return { ...c, backtestHits: hits, backtestYears: c.backtest.length };
  });

  const incomeRaw = await load("CIA02");
  const inc = incomeRaw.dimension;
  const [incStatKey, incTimeKey, incGeoKey] = incomeRaw.id;
  const keysOf = (k) => (Array.isArray(inc[k].category.index) ? inc[k].category.index : Object.keys(inc[k].category.index));
  const incStats = keysOf(incStatKey), incYears = keysOf(incTimeKey), geos = keysOf(incGeoKey);
  const INDEX = "Index of Disposable Income per Person (excluding Rent)";
  const s = incStats.findIndex((x) => inc[incStatKey].category.label[x] === INDEX);
  const yi = incYears.length - 1;
  const COUNTY_NAMES = ["Carlow","Cavan","Clare","Cork","Donegal","Dublin","Galway","Kerry","Kildare","Kilkenny","Laois","Leitrim","Limerick","Longford","Louth","Mayo","Meath","Monaghan","Offaly","Roscommon","Sligo","Tipperary","Waterford","Westmeath","Wexford","Wicklow"];
  const counties = COUNTY_NAMES.map((name) => {
    const g = geos.findIndex((x) => { const l = inc[incGeoKey].category.label[x]; return l === name || l.startsWith(`${name} City and County`) || l === `${name} County`; });
    const value = g < 0 ? null : incomeRaw.value[(s * incYears.length + yi) * geos.length + g];
    return { name, incomeIndex: value === null || value === undefined ? null : Math.round(value) };
  });

  const out = {
    source: "Central Statistics Office (CSO), Ireland",
    datasets: {
      RSM08: { title: volumeRaw.label, url: "https://data.cso.ie/table/RSM08", measure: VOLUME },
      RSM07: { title: onlineRaw.label, url: "https://data.cso.ie/table/RSM07", measure: ONLINE },
    },
    christmasYears: CHRISTMAS_YEARS,
    latestMonth: vol.monthLabel(latest),
    momentumWindow: `${vol.monthLabel(recent[0])} to ${vol.monthLabel(recent.at(-1))} vs a year earlier`,
    fetchedAt: new Date().toISOString().slice(0, 10),
    categories: scored,
    counties,
    countyIncome: { code: "CIA02", url: "https://data.cso.ie/table/CIA02", year: inc[incTimeKey].category.label[incYears[yi]], measure: INDEX },
  };
  writeFileSync(new URL("../src/data/cso.json", import.meta.url), JSON.stringify(out, null, 2));
  console.table(scored.map(({ label, novemberLift, lastBlackFridayChange, decemberLift, momentum2026, backtestHits }) => ({ label, novemberLift, lastBlackFridayChange, decemberLift, momentum2026, backtestHits })));
  console.log(counties.map((c) => `${c.name}:${c.incomeIndex}`).join(' '));
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
